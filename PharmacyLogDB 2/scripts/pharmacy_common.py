# Excel Daily Log tab parsing (backfill)
# ---------------------------------------------------------------------

def get_table_column_map(sheet, table_name, alias_map):
    """Returns (col_index_map, header_row, first_data_row, last_row)
    using the sheet's actual Excel Table definition, so we read the
    real column order instead of guessing at header text. Returns None
    if the named table isn't found on this sheet."""
    from openpyxl.utils.cell import range_boundaries

    table = sheet.tables.get(table_name) if hasattr(sheet.tables, "get") else None
    if table is None:
        return None

    min_col, min_row, max_col, max_row = range_boundaries(table.ref)
    header_row = min_row
    col_map = {}
    for i, table_col in enumerate(table.tableColumns):
        db_col = alias_map.get(_normalize(table_col.name))
        if db_col:
            col_map[min_col + i] = db_col
    return col_map, header_row, header_row + 1, max_row


def read_daily_log_sheet(sheet):
    """Returns a list of dicts (auto + manual fields, plus date_filled)
    from the '📋 Daily Log' Excel Table. Handles the 'Log Date:M/D/YY'
    separator rows your old Office Script inserts by carrying that date
    forward onto the data rows beneath it, until the next separator."""
    alias_map = dict(config.EXCEL_COLUMN_ALIASES)

    table_info = get_table_column_map(sheet, config.EXCEL_TABLE_NAME, alias_map)
    used_fallback = False
    if table_info is None:
        used_fallback = True
        col_map, header_row, first_data_row, last_row = _find_header_row_fallback(
            sheet, alias_map
        )
        if col_map is None:
            return None, used_fallback
    else:
        col_map, header_row, first_data_row, last_row = table_info

    patient_col = next((c for c, f in col_map.items() if f == "patient"), None)
    rx_col = next((c for c, f in col_map.items() if f == "rx_number"), None)

    rows = []
    current_log_date = ""
    unknown_counter = 0
    skipped_separator = 0

    for row_idx in range(first_data_row, last_row + 1):
        record = {}
        any_value = False
        for col, db_col in col_map.items():
            val = format_cell(sheet.cell(row=row_idx, column=col).value)
            if val:
                any_value = True
            record[db_col] = val

        if not any_value:
            continue  # fully blank row

        patient_val = record.get("patient", "") if patient_col else ""
        norm_patient = _normalize(patient_val)
        if norm_patient.startswith(_normalize(config.EXCEL_LOG_DATE_PREFIX)):
            # "Log Date:6/17/26" separator row — remember the date for
            # the rows that follow, don't treat it as data.
            date_part = re.split(r":", patient_val, maxsplit=1)
            if len(date_part) == 2:
                current_log_date = extract_date_key(date_part[1].strip())
            skipped_separator += 1
            continue

        rx_val = record.get("rx_number", "") if rx_col else ""
        if not rx_val:
            continue  # not a real data row (banner/blank/other stray text)

        for col_name, _ in config.ALL_FIELDS:
            record.setdefault(col_name, "")

        if current_log_date:
            record["date_filled"] = current_log_date
        else:
            unknown_counter += 1
            record["date_filled"] = f"UNKNOWN-ROW-{row_idx}"

        rows.append(record)

    meta = {
        "used_fallback": used_fallback,
        "skipped_separator": skipped_separator,
        "unknown_date_count": unknown_counter,
    }
    return rows, meta


def _find_header_row_fallback(sheet, alias_map, search_rows=15):
    """Used only if EXCEL_TABLE_NAME isn't found on the sheet (e.g. the
    real workbook doesn't use a formal Excel Table). Scans the first
    few rows for one that looks like a header, matching config's
    EXCEL_COLUMN_ALIASES."""
    best_row_idx = None
    best_score = 0
    for row_idx in range(1, min(search_rows, sheet.max_row) + 1):
        row_cells = [sheet.cell(row=row_idx, column=c).value for c in range(1, sheet.max_column + 1)]
        score = sum(1 for cell in row_cells if cell and _normalize(cell) in alias_map)
        if score > best_score:
            best_score = score
            best_row_idx = row_idx
    if best_score < 3:
        return None, None, None, None

    col_map = {}
    for c in range(1, sheet.max_column + 1):
        header_val = sheet.cell(row=best_row_idx, column=c).value
        if header_val is None:
            continue
        db_col = alias_map.get(_normalize(header_val))
        if db_col:
            col_map[c] = db_col
    return col_map, best_row_idx, best_row_idx + 1, sheet.max_row
